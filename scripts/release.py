"""Synchronize generated version declarations and fingerprint release source files."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'src/music_catalog_manager/resources'
RELEASE = json.loads((RESOURCES / 'release.json').read_text(encoding='utf-8'))


def fingerprint():
    digest = hashlib.sha256()
    for path in sorted((ROOT / 'src').rglob('*')):
        if not path.is_file() or path.suffix == '.pyc' or '__pycache__' in path.parts or '.egg-info' in str(path) or path.name == 'build-info.json':
            continue
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--stamp', action='store_true')
    parser.add_argument('--fingerprint', action='store_true')
    args = parser.parse_args()
    if args.fingerprint:
        print(fingerprint())
        return
    if not re.fullmatch(r'\d+\.\d+\.\d+', RELEASE['version']) or not re.fullmatch(r'\d+\.\d+\.\d+\.0', RELEASE['msix_version']):
        raise ValueError('Invalid release version')
    path = ROOT / 'packaging/msix/AppxManifest.xml'
    old = path.read_text(encoding='utf-8')
    updated = re.sub(r'Version="\d+\.\d+\.\d+\.\d+" ProcessorArchitecture', f'Version="{RELEASE["msix_version"]}" ProcessorArchitecture', old)
    include = ROOT / 'scripts/version.iss'
    content = f'; Generated by scripts/release.py\n#define AppVersion "{RELEASE["version"]}"\n'
    if args.check:
        if old != updated or not include.exists() or include.read_text(encoding='utf-8') != content:
            raise ValueError('Stale generated release versions; run scripts/release.py')
    else:
        path.write_text(updated, encoding='utf-8')
        include.write_text(content, encoding='utf-8')
    if args.stamp:
        (RESOURCES / 'build-info.json').write_text(json.dumps(dict(**RELEASE, source_sha256=fingerprint())), encoding='utf-8')


if __name__ == '__main__':
    main()
